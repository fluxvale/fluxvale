//! `cargo xtask openapi [--check]` — regenerate
//! `crates/fluxvale-api/src/types.rs` from the committed OpenAPI
//! artifact (ADR-0019 Am. 3: the committed spec is the contract;
//! committed types must match it, or CI reds the drift guard).

use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

const USAGE: &str = "usage: cargo xtask openapi [--check]";

fn main() -> Result<()> {
    let mut check = false;
    let mut command = None;
    for arg in std::env::args().skip(1) {
        match arg.as_str() {
            "openapi" => command = Some("openapi"),
            "--check" => check = true,
            other => bail!("{USAGE} (unknown arg {other:?})"),
        }
    }
    if command != Some("openapi") {
        bail!("{USAGE}");
    }

    let root = repo_root()?;
    let spec_path = root.join("apps/platform/priv/open_api.json");
    let types_path = root.join("crates/fluxvale-api/src/types.rs");

    let spec = std::fs::read_to_string(&spec_path)
        .with_context(|| format!("reading {}", spec_path.display()))?;
    let generated = generate(&spec).context("regenerating types from the spec failed")?;

    if check {
        let committed = std::fs::read_to_string(&types_path)
            .with_context(|| format!("reading {}", types_path.display()))?;
        if committed != generated {
            bail!(
                "{} has drifted from {} — run `cargo xtask openapi` and commit the result",
                types_path.display(),
                spec_path.display()
            );
        }
        println!("ok: types.rs matches the committed spec");
    } else {
        std::fs::write(&types_path, &generated)
            .with_context(|| format!("writing {}", types_path.display()))?;
        println!("wrote {}", types_path.display());
    }
    Ok(())
}

/// The repo root, derived from this crate's location (apps/cli/xtask) so
/// the task works from any cwd.
fn repo_root() -> Result<PathBuf> {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    manifest
        .parent() // apps/cli/
        .and_then(Path::parent) // apps/
        .and_then(Path::parent) // repo root
        .map(Path::to_path_buf)
        .context("cannot locate the repo root from CARGO_MANIFEST_DIR")
}

/// Regenerate types.rs from a spec document.
fn generate(spec_source: &str) -> Result<String> {
    let spec: serde_json::Value =
        serde_json::from_str(spec_source).context("parsing the OpenAPI artifact")?;
    let schemas = spec
        .pointer("/components/schemas")
        .and_then(|value| value.as_object())
        .context("the artifact has no components.schemas")?;

    // Normalize OpenAPI-isms typify would reject or render as
    // external-crate types:
    // - `format: uuid` / `format: date-time` map to uuid::Uuid/chrono —
    //   the CLI wants plain strings (no extra runtime deps)
    // - `type: deepObject` (an OpenAPI parameter style on the
    //   -filter schemas) is not a JSON Schema instance type — it is an
    //   object of sub-filters
    let mut normalized = serde_json::Value::Object(schemas.clone());
    normalize_for_typify(&mut normalized);

    let definitions: BTreeMap<String, schemars::schema::Schema> =
        serde_json::from_value(normalized)
            .context("schemas are not valid JSON Schema for schemars 0.8")?;

    let mut type_space = typify::TypeSpace::new(&typify::TypeSpaceSettings::default());
    type_space
        .add_ref_types(definitions)
        .context("typify rejected the schema set")?;

    let file =
        syn::parse2::<syn::File>(type_space.to_stream()).context("typify emitted invalid Rust")?;
    let rendered = prettyplease::unparse(&file);
    let formatted =
        rustfmt_wrapper::rustfmt(rendered).context("rustfmt refused the generated code")?;

    Ok(format!("{}\n{formatted}", header()))
}

/// The generated-file header: names the source artifact + the codegen
/// tool versions (read from this crate's manifest, so they can't
/// silently rot).
fn header() -> String {
    format!(
        "// Generated by `cargo xtask openapi` from apps/platform/priv/open_api.json \
         (ADR-0019 Am. 3).\n// Codegen tool versions (from apps/cli/xtask/Cargo.toml): {}.\n\
         // DO NOT EDIT BY HAND — regenerate, and CI diffs this file against the spec.\n",
        tool_versions()
    )
}

fn tool_versions() -> String {
    let manifest = include_str!("../Cargo.toml");
    let mut parts = Vec::new();
    for line in manifest.lines() {
        let line = line.trim();
        let Some((name, rest)) = line.split_once(" = \"") else {
            continue;
        };
        if name == "name" || name == "version" {
            continue;
        }
        let Some((version, _)) = rest.split_once('"') else {
            continue;
        };
        parts.push(format!("{name} {version}"));
    }
    parts.join(", ")
}

/// Drop `format` keys that typify maps to crates we refuse at runtime,
/// and rewrite non-JSON-Schema `type` values to their real shape.
fn normalize_for_typify(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Object(map) => {
            let drop_format = map.get("type").and_then(|t| t.as_str()) == Some("string")
                && map
                    .get("format")
                    .and_then(|f| f.as_str())
                    .is_some_and(|f| matches!(f, "uuid" | "date-time"));
            if drop_format {
                map.remove("format");
            }
            if map.get("type").and_then(|t| t.as_str()) == Some("deepObject") {
                map.insert(
                    "type".to_string(),
                    serde_json::Value::String("object".to_string()),
                );
            }
            for (_, child) in map.iter_mut() {
                normalize_for_typify(child);
            }
        }
        serde_json::Value::Array(items) => {
            for item in items {
                normalize_for_typify(item);
            }
        }
        _ => {}
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn committed_spec() -> String {
        std::fs::read_to_string(
            repo_root()
                .expect("repo root")
                .join("apps/platform/priv/open_api.json"),
        )
        .expect("the committed artifact")
    }

    #[test]
    fn generation_is_deterministic() {
        let spec = committed_spec();
        let first = generate(&spec).unwrap();
        let second = generate(&spec).unwrap();
        assert_eq!(first, second);
    }

    #[test]
    fn generated_types_cover_the_consumed_resources() {
        let generated = generate(&committed_spec()).unwrap();
        for name in [
            "Instance",
            "App",
            "AppVersion",
            "Wallet",
            "LedgerEntry",
            "BackupSetting",
            "BackupRun",
            "AccessGateway",
            "User",
        ] {
            assert!(
                generated.contains(&format!("pub struct {name}")),
                "no generated struct {name}"
            );
        }
    }

    #[test]
    fn generated_code_carries_the_header() {
        let generated = generate(&committed_spec()).unwrap();
        assert!(generated.starts_with("// Generated by `cargo xtask openapi`"));
        assert!(generated.contains("apps/platform/priv/open_api.json"));
        assert!(generated.contains("typify"));
    }

    #[test]
    fn header_reports_manifest_versions() {
        let versions = tool_versions();
        assert!(versions.contains("typify"), "versions: {versions}");
        assert!(versions.contains("schemars"), "versions: {versions}");
    }

    #[test]
    fn normalize_keeps_only_json_schema_types() {
        let mut value = serde_json::json!({
            "a": {"type": "string", "format": "uuid"},
            "b": {"type": "string", "format": "date-time"},
            "c": {"type": "string", "format": "email"},
            "d": {"type": "integer", "format": "int64"},
            "e": {"type": "deepObject", "properties": {}},
            "f": {"anyOf": [{"type": "string", "format": "uuid"}, {"type": "null"}]}
        });
        normalize_for_typify(&mut value);
        let rendered = serde_json::to_string(&value).unwrap();
        assert!(!rendered.contains("\"uuid\""));
        assert!(!rendered.contains("\"date-time\""));
        assert!(!rendered.contains("deepObject"));
        assert!(rendered.contains("\"email\""), "unmapped formats stay");
        assert!(rendered.contains("\"int64\""), "non-string formats stay");
    }
}
