defmodule FluxVale.OAuth.Client do
  @moduledoc """
  A dynamically registered MCP OAuth client (#766, RFC 7591).

  Public clients only (`token_endpoint_auth_method: "none"`): the MCP
  clients that use this server are native apps and CLIs, and PKCE is
  the proof — no client secret exists to leak. `redirect_uris` is the
  exact-match allowlist; `client_name` is the human label the consent
  screen shows.

  System-only rows, the RequestWindow posture: no actor-facing surface,
  an empty policies block (default forbid), and the registration
  operation's `authorize?: false` writes.
  """

  use Ash.Resource,
    otp_app: :flux_vale,
    domain: FluxVale.OAuth,
    data_layer: AshPostgres.DataLayer,
    authorizers: [Ash.Policy.Authorizer]

  alias FluxVale.OAuth.Client.RedirectUris

  postgres do
    table("oauth_clients")
    repo(FluxVale.Repo)

    # ADR-0032 §3: no DB-side id default — ids are Ash's job (see User).
    migration_defaults(id: "nil")
  end

  # Deliberately empty: with the Policy authorizer attached, a
  # policy-less action is forbidden to every actor. Registration and
  # the authorization-server lookups are system calls
  # (`authorize?: false` with comments in place).
  policies do
  end

  attributes do
    uuid_v7_primary_key(:id)

    create_timestamp(:created_at)
    update_timestamp(:updated_at)

    # The public handle the client sends back — generated by the
    # registration operation, unique by identity.
    attribute :client_id, :string do
      allow_nil?(false)
      public?(false)
      constraints(max_length: 64)
    end

    # Consent-screen label. The operation truncates and strips control
    # characters before it lands.
    attribute :client_name, :string do
      allow_nil?(false)
      default("MCP client")
      public?(false)
      constraints(max_length: 100)
    end

    attribute :redirect_uris, {:array, :string} do
      allow_nil?(false)
      default([])
      public?(false)
      constraints(max_length: 5, items: [max_length: 2048])
    end

    attribute :grant_types, {:array, :string} do
      allow_nil?(false)
      default(["authorization_code", "refresh_token"])
      public?(false)
      constraints(max_length: 2, items: [max_length: 32])
    end

    attribute :response_types, {:array, :string} do
      allow_nil?(false)
      default(["code"])
      public?(false)
      constraints(max_length: 1, items: [max_length: 16])
    end

    attribute :token_endpoint_auth_method, :string do
      allow_nil?(false)
      default("none")
      public?(false)
      constraints(match: ~r/\Anone\z/)
    end

    attribute :last_used_at, :utc_datetime do
      public?(false)
    end
  end

  actions do
    defaults([])

    create :register do
      description("System write — one dynamically registered public client")

      accept([
        :client_id,
        :client_name,
        :redirect_uris,
        :grant_types,
        :response_types,
        :token_endpoint_auth_method
      ])

      validate(RedirectUris, where: changing(:redirect_uris))
    end

    read :get_by_client_id do
      description("Resolve a client by its public handle — the AS system lookup")
      get?(true)
      argument(:client_id, :string, allow_nil?: false)
      filter(expr(client_id == ^arg(:client_id)))
    end

    read :get_by_id do
      description("Resolve a client by its row id — the settings page's name lookup")
      get?(true)
      argument(:id, :uuid, allow_nil?: false)
      filter(expr(id == ^arg(:id)))
    end

    read :created_since do
      description("Clients registered at or after the cutoff — the registration cap's count")
      argument(:since, :utc_datetime, allow_nil?: false)
      filter(expr(created_at >= ^arg(:since)))
    end

    update :touch_last_used do
      description("Stamp last_used_at — system write from the token endpoint")
      accept([])
      change(set_attribute(:last_used_at, &DateTime.utc_now/0))
    end
  end

  code_interface do
    domain(FluxVale.OAuth)

    define(:get_by_client_id, args: [:client_id])
    define(:get_by_id, args: [:id])
    define(:touch_last_used)
  end

  identities do
    identity(:unique_client_id, [:client_id])
  end
end
