defmodule Mix.Tasks.Blog.Lint do
  @shortdoc "Validates blog post frontmatter (ADR-00025)"

  @moduledoc """
  Validates the blog content SOURCE tree (`docs/blog`, the content
  home ADR-0044 gave the blog): every post's frontmatter parses and
  carries the required fields, slugs equal their filename stems,
  `og_image` paths resolve to shipped static files. Runs in `mix ci`
  (ADR-00025 §1: agent-authored posts fail CI loudly);
  `FluxVale.Blog.Loader.load!/1` re-checks the synced priv copy at
  boot.

  The default target is the repo's `docs/blog` (the authored tree —
  the priv copy is generated by `mix content.sync`). An optional
  argument lints another directory (the tests' fixture dirs ride it).
  A failing lint exits 1 with one message per problem.
  """

  use Mix.Task

  alias FluxVale.Blog.Lint

  @requirements ["app.config"]

  @impl Mix.Task
  def run(args) do
    dir = List.first(args) || source_dir()

    case Lint.check(dir) do
      :ok ->
        Mix.shell().info("blog content ok")

      {:error, errors} ->
        Enum.each(errors, &Mix.shell().error(&1))
        Mix.shell().error("mix blog.lint failed")
        exit({:shutdown, 1})
    end
  end

  # The authored tree at the repo root (ADR-0044 §1): mix runs from
  # apps/platform, so the repo root sits two levels up.
  defp source_dir, do: Path.expand("../../docs/blog", File.cwd!())
end
