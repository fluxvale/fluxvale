defmodule Mix.Tasks.Docs.Lint do
  @shortdoc "Validates public docs content (ADR-0044)"

  @moduledoc """
  Validates the public docs SOURCE tree (`docs/public`, ADR-0044):
  every file is a page in a known section directory with conforming
  frontmatter, and nothing else rides the tree. Runs in `mix ci`
  beside `mix blog.lint`; `FluxVale.Docs.Loader.load!/1` re-checks the
  synced priv copy at boot.

  The default target is the repo's `docs/public` (the authored tree —
  the priv copy is generated by `mix content.sync`). An optional
  argument lints another directory (the tests' fixture dirs ride it).
  A failing lint exits 1 with one message per problem.
  """

  use Mix.Task

  alias FluxVale.Docs.Lint

  @requirements ["app.config"]

  @impl Mix.Task
  def run(args) do
    dir = List.first(args) || source_dir()

    case Lint.check(dir) do
      :ok ->
        Mix.shell().info("docs content ok")

      {:error, errors} ->
        Enum.each(errors, &Mix.shell().error(&1))
        Mix.shell().error("mix docs.lint failed")
        exit({:shutdown, 1})
    end
  end

  # The authored tree at the repo root (ADR-0044 §1): mix runs from
  # apps/platform, so the repo root sits two levels up.
  defp source_dir, do: Path.expand("../../docs/public", File.cwd!())
end
